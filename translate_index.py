TOKEN_RE = re.compile(
    r"<!--.*?-->|<(?:script|style)\b[^>]*>[\s\S]*?</(?:script|style)\s*>|<[^>]*>",
    flags=re.IGNORECASE | re.DOTALL,
)
NUXT_SCRIPT_OPEN = re.compile(r"<script\b[^>]*\bid\s*=\s*(['\"])__NUXT_DATA__\1[^>]*>", re.I | re.S)
SCRIPT_CLOSE = re.compile(r"</script\s*>$", re.I | re.S)
LIGHT_YEARS = re.compile(r"^(\d+(?:[.,]\d+)?)\s+light years?$", re.I)


def normalized(value: str) -> str:
    return " ".join(value.split())


LOOKUP = {normalized(k): v for k, v in TRANSLATIONS.items()}
for _branch_name, distance, ra, dec, street, house in BRANCHES:
    LOOKUP[normalized(distance)] = "Бишкек"
    LOOKUP[normalized(ra)] = street
    LOOKUP[normalized(dec)] = house
    distance_value = distance.split()[0].replace(".", ",")
    LOOKUP[normalized(distance_value + " св. лет")] = "Бишкек"



def translate(value: str) -> str:
    key = normalized(value)
    if key in LOOKUP:
        return LOOKUP[key]
    light_years = LIGHT_YEARS.fullmatch(key)
    if light_years:
        return light_years.group(1).replace(".", ",") + " св. лет"
    return value


def translate_text_node(chunk: str) -> str:
    if not chunk.strip():
        return chunk
    parts = re.fullmatch(r"(\s*)(.*?)(\s*)", chunk, flags=re.S)
    if parts is None:
        return chunk
    value = translate(parts.group(2))
    if value == parts.group(2):
        return chunk
    return parts.group(1) + value + parts.group(3)


def rewrite_footer_nuxt(values: list) -> int:
    """Replace the three-paragraph contacts rich-text graph with one paragraph."""
    for item in values:
        if not isinstance(item, dict) or not isinstance(item.get("component"), int):
            continue
        component_ref = item["component"]
        if component_ref >= len(values) or values[component_ref] != "section-contacts":
            continue
        title_ref = item.get("title")
        if not isinstance(title_ref, int) or not isinstance(values[title_ref], dict):
            continue
        text_graph = values[title_ref]
        content_ref = text_graph.get("content")
        if not isinstance(content_ref, int) or not isinstance(values[content_ref], list):
            continue
        paragraphs = values[content_ref]
        if not paragraphs:
            continue
        first_paragraph_ref = paragraphs[0]
        first_paragraph = values[first_paragraph_ref]
        first_content_ref = first_paragraph.get("content") if isinstance(first_paragraph, dict) else None
        if not isinstance(first_content_ref, int) or not isinstance(values[first_content_ref], list):
            continue
        text_parts = values[first_content_ref]
        if not text_parts:
            continue
        first_text_ref = text_parts[0]
        first_text = values[first_text_ref]
        if not isinstance(first_text, dict) or not isinstance(first_text.get("text"), int):
            continue
        values[first_text["text"]] = FOOTER_TEXT
        values[content_ref] = [first_paragraph_ref]
        return 1
    return 0


def translate_nuxt_script(token: str) -> tuple[str, int]:
    opening = NUXT_SCRIPT_OPEN.match(token)
    closing = SCRIPT_CLOSE.search(token)
    if opening is None or closing is None:
        return token, 0
    payload = token[opening.end():closing.start()]
    values = json.loads(payload)
    if not isinstance(values, list):
        raise ValueError("Неожиданный формат __NUXT_DATA__")
    changed = 0
    for index, value in enumerate(values):
        if isinstance(value, str):
            new_value = translate(value)
            if new_value != value:
                values[index] = new_value
                changed += 1
    changed += rewrite_footer_nuxt(values)
    packed = json.dumps(values, ensure_ascii=False, separators=(",", ":"))
    packed = packed.replace("</", "<\\/")
    return token[:opening.end()] + packed + token[closing.start():], changed


FOOTER_H2 = re.compile(
    r'(<h2\b(?=[^>]*class="[^"]*section-contacts__title)[^>]*>)([\s\S]*?)(</h2\s*>)',
    re.I,
)


def rewrite_footer_html(source: str) -> str:
    def replace(match: re.Match[str]) -> str:
        markup = match.group(2)
        rich_text_open = re.search(r'<span\b[^>]*class="rich-text"[^>]*>', markup, re.I | re.S)
        if not rich_text_open:
            raise ValueError("Не найден блок rich-text в нижнем заголовке сайта")
        body = (
            rich_text_open.group(0)
            + '<p textAlign="null"><span style="color: ">'
            + html.escape(FOOTER_TEXT)
            + '</span></p></span>'
        )
        return match.group(1) + body + match.group(3)

    result, count = FOOTER_H2.subn(replace, source, count=1)
    if count != 1:
        raise ValueError("Не удалось найти заголовок нижнего блока section-contacts__title")
    return result


def translate_html(source: str) -> tuple[str, int, int]:
    pieces = []
    last = 0
    html_count = 0
    nuxt_count = 0
    for token_match in TOKEN_RE.finditer(source):
        before = source[last:token_match.start()]
        after = translate_text_node(before)
        if after != before:
            html_count += 1
        pieces.append(after)
        token = token_match.group(0)
        if token.lower().startswith("<script") and "__NUXT_DATA__" in token[:300]:
            token, n = translate_nuxt_script(token)
            nuxt_count += n
        pieces.append(token)
        last = token_match.end()
    remaining = source[last:]
    new_remaining = translate_text_node(remaining)
    if new_remaining != remaining:
        html_count += 1
    pieces.append(new_remaining)
    result = rewrite_footer_html("".join(pieces))
    result = re.sub(r'(<html\b[^>]*\blang\s*=\s*["\'])en_US(?=["\'])', r"\1ru", result, count=1, flags=re.I | re.S)

    def edit_meta(match: re.Match[str]) -> str:
        tag = match.group(0)
        old_description = "We tried making this real. NASA said No. So for now, it's just a delicious concept by Sunil."
        tag = tag.replace(old_description, TRANSLATIONS[old_description])
        if 'property="og:locale"' in tag:
            tag = tag.replace('content="en_US"', 'content="ru_RU"')
        return tag

    result = re.sub(r"<meta\b[^>]*>", edit_meta, result, flags=re.I | re.S)
    return result, html_count, nuxt_count


